IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[PG_CB_REMOLQUE]') AND type in (N'P', N'PC'))
	DROP PROCEDURE [dbo].[PG_CB_REMOLQUE]
GO


CREATE PROCEDURE [dbo].[PG_CB_REMOLQUE]
	@PP_L_DEBUG				INT,
	@PP_K_SISTEMA_EXE		INT,
	@PP_K_USUARIO			INT,
	--============================
	@PP_L_BORRADO			INT
AS

	SELECT	K_REMOLQUE	AS K_COMBOBOX,
			D_REMOLQUE	AS D_COMBOBOX
	FROM	REMOLQUE
	WHERE	L_BORRADO<>@PP_L_BORRADO
	ORDER BY D_REMOLQUE

	-- ////////////////////////////////////////////////////
GO




