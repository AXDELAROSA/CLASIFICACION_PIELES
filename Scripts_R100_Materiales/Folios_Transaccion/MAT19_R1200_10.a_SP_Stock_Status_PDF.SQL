CREATE PROCEDURE [dbo].[PG_GET_DEFECTO_X_LOCACION_COLOR_LOTE]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO				INT,
	--============================
	@PP_LOCACION		VARCHAR(50),
	@PP_COLOR			VARCHAR(50),
	@PP_LOTE			VARCHAR(50)
AS

	SELECT	ISNULL(( SELECT TOP 1 TRADUCCION FROM [PPMS_PEARL].[dbo].DEF WHERE CLAVE = RP_SC.DEFECTO), '') AS DEFECTO, 
			COUNT(ID) AS N_HIDE, 
			SUM(CONVERT(DECIMAL(13,4), LTRIM(RTRIM(SQF)))) AS SQF
	FROM	RP_SC 
	WHERE MOVEMENT = @PP_LOCACION
	AND COLOUR = @PP_COLOR
	AND LOT = @PP_LOTE
	AND RP_SC.DEFECTO IS NOT NULL
	AND RP_SC.DEFECTO <> ''
	GROUP BY RP_SC.DEFECTO
		
	-- ////////////////////////////////////////////////////
GO



