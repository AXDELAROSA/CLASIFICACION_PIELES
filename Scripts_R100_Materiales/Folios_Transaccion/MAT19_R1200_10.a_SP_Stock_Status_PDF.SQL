/*
	EXECUTE [PG_CB_LOCACION_STOCK_STATUS] 001,144, 0
	EXECUTE	[dbo].[PG_STOCK_STATUS_PDF] 0,144, 1, 96, 0
	EXECUTE	[dbo].[PG_STOCK_STATUS_PDF] 0,144, 'MQU', 6, 'MSL', 7, 0, 0 --ALMACEN
*/
CREATE PROCEDURE [dbo].[PG_STOCK_STATUS_PDF]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================
	@PP_LOCACION_INICIAL_STR	VARCHAR(50),
	@PP_LOCACION_INICIAL		INT,
	@PP_LOCACION_FINAL_STR		VARCHAR(50),
	@PP_LOCACION_FINAL			INT,
	@PP_SQF_MENOR_1000			INT,
	@PP_VER_DEFECTO_LOTE		INT
AS
	
	DECLARE @VP_TA_LOCACION	AS TABLE
	(	K_LOCACION		INT IDENTITY(1,1),
		D_LOCACION		VARCHAR(50)
	)

	DECLARE @TBL_IMLSMST_SQL_SQF_X_LOTE	AS TABLE
	(	LOCACION		VARCHAR(50),
		D_LOCACION		VARCHAR(255),
		COLOR			VARCHAR(50),
		LOTE			VARCHAR(50),
		SQF_DISPONIBLE	DECIMAL(13,4)
	)

	INSERT INTO @VP_TA_LOCACION 	
	SELECT LTRIM(RTRIM(LOC))
	FROM  IMLOCFIL_SQL (NOLOCK)
	WHERE user_def_fld_1  IS NULL
	AND ri_mrb_loc <> ''
	ORDER BY ri_mrb_loc ASC	
	 
	IF @PP_SQF_MENOR_1000 = 1
		BEGIN
			INSERT INTO @TBL_IMLSMST_SQL_SQF_X_LOTE
			SELECT  --TOP 1
					LTRIM(RTRIM(IMLOCFIL_SQL.loc)) LOCACION, 
					LTRIM(RTRIM(IMLOCFIL_SQL.loc_desc)) AS D_LOCACION, 
					SUBSTRING(LTRIM(RTRIM(IMLSMST_SQL.item_no)), 1, 7) AS COLOR,
					LTRIM(RTRIM(IMLSMST_SQL.ser_lot_no)) AS LOTE,
					CONVERT(DECIMAL(13,4), qty_on_hand) AS SQF_DISPONIBLE
			FROM	IMLSMST_SQL	 (NOLOCK)
			INNER JOIN IMLOCFIL_SQL  (NOLOCK) ON IMLSMST_SQL.loc = IMLOCFIL_SQL.LOC
			WHERE IMLSMST_SQL.loc IN (	SELECT D_LOCACION 
							FROM @VP_TA_LOCACION 
							WHERE K_LOCACION BETWEEN @PP_LOCACION_INICIAL AND @PP_LOCACION_FINAL
						)
			AND item_no <> ''
			AND qty_on_hand > 0
			AND qty_on_hand < 1000
			AND SUBSTRING(LTRIM(RTRIM(IMLSMST_SQL.item_no)), 1, 1) = 'F'
		END
	ELSE
		BEGIN
			INSERT INTO @TBL_IMLSMST_SQL_SQF_X_LOTE
			SELECT  --TOP 1
					LTRIM(RTRIM(IMLOCFIL_SQL.loc)) LOCACION, 
					LTRIM(RTRIM(IMLOCFIL_SQL.loc_desc)) AS D_LOCACION, 
					SUBSTRING(LTRIM(RTRIM(IMLSMST_SQL.item_no)), 1, 7) AS COLOR,
					LTRIM(RTRIM(IMLSMST_SQL.ser_lot_no)) AS LOTE,
					CONVERT(DECIMAL(13,4), qty_on_hand) AS SQF_DISPONIBLE
			FROM	IMLSMST_SQL	 (NOLOCK)
			INNER JOIN IMLOCFIL_SQL  (NOLOCK) ON IMLSMST_SQL.loc = IMLOCFIL_SQL.LOC
			WHERE IMLSMST_SQL.loc IN (	SELECT D_LOCACION 
							FROM @VP_TA_LOCACION 
							WHERE K_LOCACION BETWEEN @PP_LOCACION_INICIAL AND @PP_LOCACION_FINAL
						)
			AND item_no <> ''
			AND qty_on_hand > 0
			AND SUBSTRING(LTRIM(RTRIM(IMLSMST_SQL.item_no)), 1, 1) = 'F'
		END

		DECLARE @TBL_TOTAL_SQF_X_LOTE	AS TABLE
	(	LOCACION		VARCHAR(50),
		D_LOCACION		VARCHAR(255),
		COLOR			VARCHAR(50),
		D_COLOR			VARCHAR(255),
		LOTE			VARCHAR(50),
		SQF_DISPONIBLE	DECIMAL(13,4),
		N_PIEL			INT,
		SQF_PIEL		DECIMAL(13,4),
		VALIDAR_SQF		INT DEFAULT 0
	)

		DECLARE @VP_LOCACION	VARCHAR(50) = '', @VP_D_LOCACION	VARCHAR(255) = '', @VP_COLOR	VARCHAR(100) = '';
		DECLARE @VP_LOTE	VARCHAR(50) = '', @VP_SQF_DISPONIBLE DECIMAL(13,4) = 0;

		DECLARE CU_SQF_DISPONIBLE_X_LOTE CURSOR 
		FOR SELECT LOCACION,
			   D_LOCACION,		
			   COLOR,			
			   LOTE,			
			   SQF_DISPONIBLE
		FROM @TBL_IMLSMST_SQL_SQF_X_LOTE

		OPEN CU_SQF_DISPONIBLE_X_LOTE
		FETCH NEXT FROM CU_SQF_DISPONIBLE_X_LOTE INTO @VP_LOCACION, @VP_D_LOCACION, @VP_COLOR, @VP_LOTE, @VP_SQF_DISPONIBLE
			
		WHILE @@FETCH_STATUS = 0
			BEGIN
				DECLARE @VP_D_COLOR  VARCHAR(255)= '', @VP_N_PIEL INT = 0, @VP_SQF_PIEL DECIMAL(13, 4) = 0, @VP_COLOR_CONTROLADO INT = 0;
				
				SELECT TOP 1 @VP_D_COLOR = LTRIM(RTRIM(ITEM_DESC_1)) 
				FROM	IMITMIDX_SQL 
				WHERE LTRIM(RTRIM(item_no)) = @VP_COLOR

				SELECT @VP_COLOR_CONTROLADO = COUNT(ID) 
				FROM COLORES_CONTROLADOS (NOLOCK)
				WHERE COLOR = @VP_COLOR
				
				IF ( @VP_COLOR_CONTROLADO = 0 OR @VP_COLOR_CONTROLADO IS NULL )
					BEGIN
						SET @VP_N_PIEL = @VP_SQF_DISPONIBLE / 40
						INSERT INTO @TBL_TOTAL_SQF_X_LOTE(	LOCACION, D_LOCACION, COLOR, D_COLOR, LOTE, SQF_DISPONIBLE, N_PIEL, SQF_PIEL
														)
													VALUES(
															 @VP_LOCACION, @VP_D_LOCACION, @VP_COLOR, @VP_D_COLOR, @VP_LOTE, @VP_SQF_DISPONIBLE, @VP_N_PIEL, @VP_SQF_PIEL
															)
					END										
				ELSE
					BEGIN
						SELECT	@VP_N_PIEL = COUNT(ID),
								@VP_SQF_PIEL = SUM(CONVERT(DECIMAL(13,2),LTRIM(RTRIM(SQF)))) 
						FROM RP_SC
						WHERE MOVEMENT = @VP_LOCACION
						AND COLOUR = @VP_COLOR
						AND RIGHT( '000000' + LTRIM(RTRIM(LOT)), 6) = @VP_LOTE

						IF @VP_N_PIEL IS NULL
							SET @VP_N_PIEL = 0

						IF @VP_SQF_PIEL IS NULL
							SET @VP_SQF_PIEL =0

						INSERT INTO @TBL_TOTAL_SQF_X_LOTE(	LOCACION, D_LOCACION, COLOR, D_COLOR, LOTE, SQF_DISPONIBLE, N_PIEL, SQF_PIEL, VALIDAR_SQF
														)
													VALUES(
															 @VP_LOCACION, @VP_D_LOCACION, @VP_COLOR, @VP_D_COLOR, @VP_LOTE, @VP_SQF_DISPONIBLE, @VP_N_PIEL, @VP_SQF_PIEL, 1
															)
					END

				FETCH NEXT FROM CU_SQF_DISPONIBLE_X_LOTE INTO @VP_LOCACION, @VP_D_LOCACION, @VP_COLOR, @VP_LOTE, @VP_SQF_DISPONIBLE
			END
	
		CLOSE CU_SQF_DISPONIBLE_X_LOTE
		DEALLOCATE CU_SQF_DISPONIBLE_X_LOTE


		SELECT LOCACION,
			   RESULTADO.D_LOCACION,		
			   COLOR,	
			   D_COLOR,
			   --LOTE,	
			   ( CASE WHEN SUBSTRING(LOTE, 1, 1) = '0' THEN SUBSTRING(LOTE, 2, 10 ) 
					ELSE LOTE END ) AS LOTE,		
			   SQF_DISPONIBLE,	
			   N_PIEL,			
			   SQF_PIEL,
			   VALIDAR_SQF
		FROM @TBL_TOTAL_SQF_X_LOTE AS RESULTADO
		INNER JOIN @VP_TA_LOCACION AS ORD_LOC ON ORD_LOC.D_LOCACION = RESULTADO.LOCACION
		--ORDER BY  RESULTADO.D_LOCACION, COLOR, LOTE
		ORDER BY ORD_LOC.K_LOCACION, RESULTADO.D_LOCACION, COLOR, LOTE
	-----////////////////////////////////////////////////////////////////
	-- //////////////////////////////////////////////////////////////////
GO


