CREATE PROCEDURE [dbo].[PG_CB_LOCACION_STOCK_STATUS]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO				INT,
	--============================
	@PP_L_CON_TODOS				INT
AS

	DECLARE @VP_TA_CATALOGO	AS TABLE
	(	TA_K_CATALOGO		INT IDENTITY(1,1),
		TA_D_CATALOGO		VARCHAR(50))

	INSERT INTO @VP_TA_CATALOGO 	
	SELECT LTRIM(RTRIM(LOC))
	FROM  IMLOCFIL_SQL  (NOLOCK)
	WHERE user_def_fld_1  IS NULL
	AND ri_mrb_loc <> ''
	ORDER BY ri_mrb_loc ASC
	
	IF @PP_L_CON_TODOS = 0
		BEGIN

			SELECT	TA_K_CATALOGO	AS K_COMBOBOX,
				TA_D_CATALOGO	AS D_COMBOBOX 
			FROM	@VP_TA_CATALOGO
			ORDER BY  TA_K_CATALOGO  
		END
	ELSE
		BEGIN
			SELECT	TA_K_CATALOGO	AS K_COMBOBOX,
				TA_D_CATALOGO	AS D_COMBOBOX 
			FROM	@VP_TA_CATALOGO
			WHERE TA_K_CATALOGO >= @PP_L_CON_TODOS
			ORDER BY  TA_K_CATALOGO  
		END
		
	-- ==========================================
		
	-- ////////////////////////////////////////////////////
GO


