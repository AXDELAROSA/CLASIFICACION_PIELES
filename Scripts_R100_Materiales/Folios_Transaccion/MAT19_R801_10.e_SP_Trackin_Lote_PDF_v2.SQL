CREATE PROCEDURE [dbo].[PG_CB_COLOR_LOT_TRACK_X_COLOR]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO				INT,
	--============================
	@PP_L_CON_TODOS				INT
AS
	DECLARE @VP_TA_CATALOGO	AS TABLE
				(	TA_K_CATALOGO		VARCHAR(50),
					TA_D_CATALOGO		VARCHAR(150)
				)
		-- ==========================================



		IF @PP_L_CON_TODOS=0
			BEGIN
				INSERT INTO @VP_TA_CATALOGO 
				SELECT	LTRIM(RTRIM(ITEM_NO))		AS TA_K_CATALOGO,
						CONCAT(LTRIM(RTRIM(ITEM_NO)), ' (', LTRIM(RTRIM(item_desc_1)), ')')	AS TA_D_CATALOGO					
				FROM IMITMIDX_SQL (NOLOCK)
				WHERE ITEM_NO IN (SELECT COLOR FROM [DATA_02].DBO.COLORES_CONTROLADOS (NOLOCK) WHERE COLOR <> 'FMCKSTT')
				AND LEN(RTRIM(LTRIM(ITEM_NO)))=7				
			END
	

		SELECT	TA_K_CATALOGO	AS K_COMBOBOX,
				TA_D_CATALOGO	AS D_COMBOBOX 
		FROM	@VP_TA_CATALOGO
		ORDER BY TA_K_CATALOGO
		
