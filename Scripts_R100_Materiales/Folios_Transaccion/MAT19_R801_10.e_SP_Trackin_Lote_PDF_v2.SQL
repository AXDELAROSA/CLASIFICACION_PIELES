	EXECUTE	[dbo].[PG_TRACKING_LOTE_YIELD_X_COLOR_RESUMEN_PDF] 0,0, 'FMCKTX7','34041'
	EXECUTE	[dbo].[PG_TRACKING_LOTE_YIELD_PROMEDIO_X_COLOR_RESUMEN_PDF] 0,0, 'FMCKTX7','34041'
*/
CREATE PROCEDURE [dbo].[PG_TRACKING_LOTE_X_COLOR_SUMARY_PDF]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================
	@PP_COLOR					VARCHAR(20),
	@PP_YEAR					INT
AS
	
	
	-- ////////////SE CREA TABLA TEMPORAL///////////////////////////////
	DECLARE @VP_TBL_SUMARY_X_LOTE AS TABLE(
		ID			INT IDENTITY(1,1),
		LOTE		VARCHAR(20),
		LOCACION	VARCHAR(20),
		TOTAL_PIEL	INT,
		TOTAL_SQF	DECIMAL(13,2)
	)
	
	-- ////////////SE DECLARAN VARIABLES A USARSE///////////////////////////////
	DECLARE @VP_LOTE VARCHAR (50) = '', @VP_TOTAL_PIEL_RECIBIDA INT = 0, @VP_TOTAL_SQF_RECIBIDO DECIMAL(13,2) = 0;

	-- ////////////SE CREA CURSOR PARA LOS DIFERENTES LOTES///////////////////////////////
	DECLARE CU_LOTE_IMPORTADO_X_COLOR CURSOR 
	FOR SELECT --TOP 50
			PLOT AS LOTE,
			SUM(CONVERT(INT, LTRIM(RTRIM(THIDES)))) AS PIELES,
			SUM(CONVERT(DECIMAL(13,2), LTRIM(RTRIM(TAREA)))) AS SQF
		FROM HIDESHDR_SQL   (NOLOCK)
		WHERE	PCOLOR = @PP_COLOR
		AND YEAR(CONVERT(DATE, LDATE)) = @PP_YEAR
		AND SUBSTRING(INVOICE,1, 7) <> 'CORTADA'
		--AND INVOICE <> 'CORTADA-111111'
		GROUP BY PLOT
	
	OPEN CU_LOTE_IMPORTADO_X_COLOR
	FETCH NEXT FROM CU_LOTE_IMPORTADO_X_COLOR INTO @VP_LOTE, @VP_TOTAL_PIEL_RECIBIDA, @VP_TOTAL_SQF_RECIBIDO
	
	WHILE @@FETCH_STATUS = 0
		BEGIN
			-- ///////SE INGRESA EL SUMARY DE LO RECIVIDO/IMPORTADO////////////////////////////////////
			INSERT INTO @VP_TBL_SUMARY_X_LOTE
			SELECT	@VP_LOTE,
					'RECEIVED',
					@VP_TOTAL_PIEL_RECIBIDA,
					@VP_TOTAL_SQF_RECIBIDO

			-- ///////SE INGRESA EL SUMARY DE LAS LOCACIONES QUE NO SON DE PRODUCCION////////////////////////////////////
			INSERT INTO @VP_TBL_SUMARY_X_LOTE
			SELECT	@VP_LOTE,
					LTRIM(RTRIM(MOVEMENT)),
					COUNT(ID),
					SUM(CONVERT(DECIMAL(13,2),LTRIM(RTRIM(SQF))))
			FROM RP_SC  (NOLOCK)
			WHERE LOT = @VP_LOTE
			AND COLOUR = @PP_COLOR
			AND SUBSTRING(LTRIM(RTRIM(MOVEMENT)), 1,1 ) NOT IN ('T', 'G') 
			AND HIDE IN (	SELECT HIDE
							FROM	HIDESHDR_SQL   
							INNER JOIN	HIDESLIN_SQL ON HIDESLIN_SQL.FILENO = HIDESHDR_SQL.FILENO
							WHERE	PCOLOR = @PP_COLOR
							AND PLOT = @VP_LOTE
							AND YEAR(CONVERT(DATE, LDATE)) = @PP_YEAR
							AND SUBSTRING(INVOICE,1, 7) <> 'CORTADA'
							--AND INVOICE <> 'CORTADA-111111'
						)
			GROUP BY LTRIM(RTRIM(MOVEMENT))

			-- ///////SE INGRESA EL SUMARY DE LAS LOCACIONES QUE SON DE PRODUCCION////////////////////////////////////
			INSERT INTO @VP_TBL_SUMARY_X_LOTE
			SELECT	@VP_LOTE,
					'WIP',
					COUNT(ID),
					SUM(CONVERT(DECIMAL(13,2),LTRIM(RTRIM(SQF))))
			FROM RP_SC  (NOLOCK)
			WHERE LOT = @VP_LOTE
			AND COLOUR = @PP_COLOR
			AND SUBSTRING(LTRIM(RTRIM(MOVEMENT)), 1,1 ) IN ('T', 'G')
			AND HIDE IN (	SELECT HIDE
							FROM	HIDESHDR_SQL   
							INNER JOIN	HIDESLIN_SQL ON HIDESLIN_SQL.FILENO = HIDESHDR_SQL.FILENO
							WHERE	PCOLOR = @PP_COLOR
							AND PLOT = @VP_LOTE
							AND YEAR(CONVERT(DATE, LDATE)) = @PP_YEAR
							AND SUBSTRING(INVOICE,1, 7) <> 'CORTADA'
							--AND INVOICE <> 'CORTADA-111111'
						)

			-- ///////SE INGRESA EL SUMARY DE PIELES DE ORDENES CERRADAS////////////////////////////////////
			INSERT INTO @VP_TBL_SUMARY_X_LOTE
			SELECT	@VP_LOTE,
					'INVOICED',
					COUNT(ID),
					SUM(CONVERT(DECIMAL(13,2),LTRIM(RTRIM(SQF))))
			FROM RP_SC_FOLIO_STATUS_XX  (NOLOCK)
			WHERE LOT = @VP_LOTE
			AND COLOUR = @PP_COLOR
			--AND SUBSTRING(LTRIM(RTRIM(MOVEMENT)), 1,1 ) IN ('T', 'G') 
			AND HIDE IN (	SELECT HIDE
							FROM	HIDESHDR_SQL   
							INNER JOIN	HIDESLIN_SQL ON HIDESLIN_SQL.FILENO = HIDESHDR_SQL.FILENO
							WHERE	PCOLOR = @PP_COLOR
							AND PLOT = @VP_LOTE
							AND YEAR(CONVERT(DATE, LDATE)) = @PP_YEAR
							AND SUBSTRING(INVOICE,1, 7) <> 'CORTADA'
							--AND INVOICE <> 'CORTADA-111111'
						)

			-- ///////SE OBTIENE EL TOTAL DE PIELES Y SQF DE LO NO RECIBIDO////////////////////////////////////
			DECLARE @VP_TOTAL_PIEL INT = 0, @VP_TOTAL_SQF DECIMAL(13,2) = 0
			
			SELECT	@VP_TOTAL_PIEL = SUM(TOTAL_PIEL),
					@VP_TOTAL_SQF = SUM(TOTAL_SQF)
			FROM @VP_TBL_SUMARY_X_LOTE 
			WHERE TOTAL_PIEL > 0
			AND LOTE = @VP_LOTE
			AND LOCACION <> 'RECEIVED'

			IF ( @VP_TOTAL_PIEL > @VP_TOTAL_PIEL_RECIBIDA AND @VP_TOTAL_SQF > @VP_TOTAL_SQF_RECIBIDO )
				BEGIN
					DECLARE @VP_PIEL_EXCESS INT = @VP_TOTAL_PIEL - @VP_TOTAL_PIEL_RECIBIDA
					DECLARE @VP_SQF_EXCESS DECIMAL(13,2) = @VP_TOTAL_SQF - @VP_TOTAL_SQF_RECIBIDO
					INSERT INTO @VP_TBL_SUMARY_X_LOTE
					SELECT	@VP_LOTE,
							'EXCESS',
							@VP_PIEL_EXCESS,
							@VP_SQF_EXCESS
				END

			IF ( @VP_TOTAL_PIEL < @VP_TOTAL_PIEL_RECIBIDA AND @VP_TOTAL_SQF < @VP_TOTAL_SQF_RECIBIDO )
				BEGIN
					DECLARE @VP_PIEL_NOT_FOUND INT = @VP_TOTAL_PIEL_RECIBIDA - @VP_TOTAL_PIEL
					DECLARE @VP_SQF_NOT_FOUND  DECIMAL(13,2) = @VP_TOTAL_SQF_RECIBIDO - @VP_TOTAL_SQF
					INSERT INTO @VP_TBL_SUMARY_X_LOTE
					SELECT	@VP_LOTE,
							'NOT FOUND',
							@VP_PIEL_NOT_FOUND,
							@VP_SQF_NOT_FOUND
				END

			-- ///////SE OBTIENE EL TOTAL DE PIELES Y SQF DE LO NO RECIBIDO////////////////////////////////////
			SET @VP_TOTAL_PIEL = 0
			SET @VP_TOTAL_SQF  = 0
			
			SELECT	@VP_TOTAL_PIEL = SUM(TOTAL_PIEL),
					@VP_TOTAL_SQF = SUM(TOTAL_SQF)
			FROM @VP_TBL_SUMARY_X_LOTE 
			WHERE TOTAL_PIEL > 0
			AND LOTE = @VP_LOTE
			AND LOCACION <> 'RECEIVED'

			INSERT INTO @VP_TBL_SUMARY_X_LOTE
			SELECT	@VP_LOTE,
					'TOTAL',
					@VP_TOTAL_PIEL,
					@VP_TOTAL_SQF

			-- ////////////////////////////////////////////////////////////////////	
			FETCH NEXT FROM CU_LOTE_IMPORTADO_X_COLOR INTO @VP_LOTE, @VP_TOTAL_PIEL_RECIBIDA, @VP_TOTAL_SQF_RECIBIDO	
		END
	
	CLOSE CU_LOTE_IMPORTADO_X_COLOR
	DEALLOCATE CU_LOTE_IMPORTADO_X_COLOR
			
	-- //////SE MUESTRA EL RESULTADO//////////////////////////////////////////////////////////////	
	-- ////////////SE CREA TABLA TEMPORAL SUMMARY TOTAL///////////////////////////////
	DECLARE @VP_TBL_SUMMARY_X_TOTAL AS TABLE(
		LOCACION	VARCHAR(20),
		TOTAL_PIEL	INT,
		TOTAL_SQF	DECIMAL(13,2)
	)

	INSERT INTO @VP_TBL_SUMMARY_X_TOTAL
	SELECT LOCACION,
			SUM(TOTAL_PIEL) AS TOTAL_PIEL,
			SUM(TOTAL_SQF) AS TOTAL_SQF			 
	FROM @VP_TBL_SUMARY_X_LOTE 
	WHERE LOCACION = 'RECEIVED'
	AND TOTAL_PIEL > 0
	GROUP BY LOCACION

	INSERT INTO @VP_TBL_SUMMARY_X_TOTAL
	SELECT LOCACION,
			SUM(TOTAL_PIEL) AS TOTAL_PIEL,
			SUM(TOTAL_SQF) AS TOTAL_SQF			 
	FROM @VP_TBL_SUMARY_X_LOTE 
	WHERE LOCACION NOT IN ( 'RECEIVED', 'TOTAL', 'INVOICED')
	AND TOTAL_PIEL > 0
	GROUP BY LOCACION

	INSERT INTO @VP_TBL_SUMMARY_X_TOTAL
	SELECT LOCACION,
			SUM(TOTAL_PIEL) AS TOTAL_PIEL,
			SUM(TOTAL_SQF) AS TOTAL_SQF			 
	FROM @VP_TBL_SUMARY_X_LOTE 
	WHERE LOCACION = 'INVOICED'
	AND TOTAL_PIEL > 0
	GROUP BY LOCACION

	INSERT INTO @VP_TBL_SUMMARY_X_TOTAL
	SELECT LOCACION,
			SUM(TOTAL_PIEL) AS TOTAL_PIEL,
			SUM(TOTAL_SQF) AS TOTAL_SQF			 
	FROM @VP_TBL_SUMARY_X_LOTE 
	WHERE LOCACION = 'TOTAL'
	AND TOTAL_PIEL > 0
	GROUP BY LOCACION

	SELECT * FROM @VP_TBL_SUMMARY_X_TOTAL
	-----////////////////////////////////////////////////////////////////
	-- //////////////////////////////////////////////////////////////////
GO




