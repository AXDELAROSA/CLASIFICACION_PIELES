	EXECUTE	[dbo].[PG_TRACKING_LOTE_YIELD_PROMEDIO_X_COLOR_RESUMEN_PDF] 0,0, 'FCNPDX9','800071'
*/
CREATE PROCEDURE [dbo].[PG_TRACKING_LOTE_X_COLOR_DETALLE_PDF]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================
	@PP_COLOR					VARCHAR(20),
	@PP_F_INICIAL				DATE,
	@PP_F_FIN					DATE,
	@PP_LOTE					VARCHAR(20)
AS

	-- ////////////SE CREA TABLA TEMPORAL///////////////////////////////
	DECLARE @VP_TBL_PIEL_X_LOTE AS TABLE(
		ID			INT IDENTITY(1,1),
		LOCACION	VARCHAR(20),
		COLOR		VARCHAR(20),
		LOTE		VARCHAR(20),
		PIEL		VARCHAR(10),
		SQF			DECIMAL(13,2),
		FOLIO		INT,
		ORDEN		VARCHAR(20)
	)

	-- //////////SE INGRESAN LAS PIELES QUE SE ENCUENTRAN EN RP_SC/////////////////////////////////
	INSERT INTO @VP_TBL_PIEL_X_LOTE
	SELECT	LTRIM(RTRIM(MOVEMENT)),
			LTRIM(RTRIM(COLOUR)),
			RIGHT('000000' + LTRIM(RTRIM(LOT)), 6) ,
			LTRIM(RTRIM(HIDE)),
			LTRIM(RTRIM(CONVERT(DECIMAL(13,2),SQF))),
			TAGNO,
			-- ===========================
			( CASE WHEN SUBSTRING(LTRIM(RTRIM(MOVEMENT)), 1,1) IN ('T', 'G')
					THEN (  SELECT TOP 1 ISNULL(JOBNO, '') 
							FROM RP_Folios (NOLOCK)
							WHERE TAG = TAGNO	) 
					ELSE 'N/A' END) AS ORDEN
			-- ===========================
	FROM RP_SC  (NOLOCK)
	WHERE LOT = @PP_LOTE
	AND COLOUR = @PP_COLOR
	AND HIDE IN (	SELECT HIDE
							FROM	HIDESHDR_SQL   
							INNER JOIN	HIDESLIN_SQL ON HIDESLIN_SQL.FILENO = HIDESHDR_SQL.FILENO
							WHERE	PCOLOR = @PP_COLOR
							AND PLOT = @PP_LOTE
							AND CONVERT(DATE, LDATE) >= @PP_F_INICIAL
							AND CONVERT(DATE, LDATE) <= @PP_F_FIN
							AND SUBSTRING(INVOICE,1, 7) <> 'CORTADA'
							--AND INVOICE <> 'CORTADA-111111'
						)
	ORDER BY MOVEMENT, HIDE

	-- ///////SE INGRESAN LAS PIELES DE ORDENES CERRADAS QUE SE ENCUENTRAN EN RP_SC_FOLIO_STATUS_XX////////////////////////////////////
	INSERT INTO @VP_TBL_PIEL_X_LOTE
	SELECT	LTRIM(RTRIM('INVOICED')),
			LTRIM(RTRIM(COLOUR)),
			RIGHT('000000' + LTRIM(RTRIM(LOT)), 6),
			LTRIM(RTRIM(HIDE)),
			LTRIM(RTRIM(CONVERT(DECIMAL(13,2),SQF))) AS SQF,
			TAGNO,
			-- ===========================
			( CASE WHEN SUBSTRING(LTRIM(RTRIM(MOVEMENT)), 1,1) IN ('T', 'G')
					THEN (  SELECT TOP 1 ISNULL(JOBNO, '') 
							FROM RP_Folios (NOLOCK)
							WHERE TAG = TAGNO	) 
					ELSE 'N/A' END) AS ORDEN
			-- ===========================
	FROM RP_SC_FOLIO_STATUS_XX  (NOLOCK)
	WHERE LOT = @PP_LOTE
	AND COLOUR = @PP_COLOR
	AND HIDE IN (	SELECT HIDE
							FROM	HIDESHDR_SQL   
							INNER JOIN	HIDESLIN_SQL ON HIDESLIN_SQL.FILENO = HIDESHDR_SQL.FILENO
							WHERE	PCOLOR = @PP_COLOR
							AND PLOT = @PP_LOTE
							AND CONVERT(DATE, LDATE) >= @PP_F_INICIAL
							AND CONVERT(DATE, LDATE) <= @PP_F_FIN
							AND SUBSTRING(INVOICE,1, 7) <> 'CORTADA'
							--AND INVOICE <> 'CORTADA-111111'
						)
	ORDER BY MOVEMENT, HIDE

	-- /////SE MUESTRA EL RESULTADO//////////////////////////////////////
	SELECT ID,
			LOCACION,
		   COLOR,	
		   CONVERT(INT, LOTE) AS LOTE,		
		   PIEL,	
		   SQF,		
		   FOLIO,	
		   ORDEN,
		   -- ===========================
		   ( CASE WHEN JOBNO IS NULL THEN 0
				ELSE CONVERT(DECIMAL(13,2), (rawpatternsqm / hidesqm) * 100) END ) AS YIELD,
		   -- ===========================
		   ( CASE	WHEN SUBSTRING(LTRIM(RTRIM(LOCACION)), 1,1) NOT IN ('T', 'G', 'F') AND JOBNO IS NULL THEN ''
					WHEN SUBSTRING(LTRIM(RTRIM(LOCACION)), 1,1) IN ('T', 'G', 'F') AND JOBNO IS NULL THEN 'PENDING'
				ELSE	'CUT' END ) AS ESTATUS
		  -- ===========================
	FROM @VP_TBL_PIEL_X_LOTE AS PIEL_DISPONIBLE
	LEFT JOIN cccuthst_sql  (NOLOCK) ON PIEL_DISPONIBLE.ORDEN = cccuthst_sql.jobno 
	AND LTRIM(RTRIM(cccuthst_sql.lotno)) = PIEL_DISPONIBLE.LOTE 
	AND PIEL_DISPONIBLE.PIEL = cccuthst_sql.hideno
	AND LTRIM(RTRIM(cccuthst_sql.COLOUR)) = @PP_COLOR
	ORDER BY ID
	
	-----////////////////////////////////////////////////////////////////
	-- //////////////////////////////////////////////////////////////////
GO




