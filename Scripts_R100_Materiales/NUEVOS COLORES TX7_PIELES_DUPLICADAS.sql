	DECLARE @TBL_PIELES_DUPPLICADAS_FINAL TABLE(
	ID			INT,
	[COLOUR]	VARCHAR(20),
	[LOT]		VARCHAR(20),
	[HIDE]		VARCHAR(20),
	[SQF]		VARCHAR(20),
	[TAGNO]		INT,
	[TYPE]		VARCHAR(20),
	[MOVEMENT] VARCHAR(20)
	)

	DECLARE @VP_LOTE VARCHAR(20) = ''
	DECLARE @VP_HIDE VARCHAR(10) = ''
	DECLARE @VP_N_HIDE VARCHAR(10) = ''
	DECLARE @VP_FOLIO INT = 0

	DECLARE CU_PIELES_DUPLICADAS CURSOR 
	FOR SELECT TAGNO, LTRIM(RTRIM(LOT)), LTRIM(RTRIM(HIDE)), LTRIM(RTRIM(SQF)) FROM RP_SC_FOLIO_TYPE_2 
	WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUPD2' 
	AND TAGNO IN (3789866, 3789868, 3789871, 3789872, 3789893, 3789894, 3789987, 3790059, 3790064, 3790065, 3790067, 3790078)
	ORDER BY LOT, HIDE

	
	OPEN CU_PIELES_DUPLICADAS
	FETCH NEXT FROM CU_PIELES_DUPLICADAS INTO @VP_FOLIO, @VP_LOTE, @VP_HIDE, @VP_N_HIDE
	
	WHILE @@FETCH_STATUS = 0
		BEGIN	
			IF (SELECT COUNT(ID) FROM @TBL_PIELES_DUPPLICADAS_FINAL WHERE LOT = @VP_LOTE AND HIDE = @VP_HIDE AND SQF = @VP_N_HIDE ) = 0
				BEGIN
					INSERT INTO @TBL_PIELES_DUPPLICADAS_FINAL
						SELECT TOP 1 ID, [COLOUR], [LOT], [HIDE], [SQF], [TAGNO], [TYPE], [MOVEMENT] 
						FROM RP_SC_FOLIO_TYPE_2 
						WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUPD2' 
						AND TAGNO = @VP_FOLIO --IN (3789866, 3789868, 3789871, 3789872, 3789893, 3789894, 3789987, 3790059, 3790064, 3790065, 3790067)
						AND LOT = @VP_LOTE
						AND HIDE = @VP_HIDE
						AND SQF = @VP_N_HIDE
				END


			FETCH NEXT FROM CU_PIELES_DUPLICADAS INTO @VP_FOLIO, @VP_LOTE, @VP_HIDE, @VP_N_HIDE
		END
	CLOSE CU_PIELES_DUPLICADAS
	DEALLOCATE CU_PIELES_DUPLICADAS

	SELECT  LOT, HIDE, COUNT(*) 
	FROM @TBL_PIELES_DUPPLICADAS_FINAL
	GROUP BY  LOT, HIDE 
	HAVING COUNT(*)>1
	ORDER BY LOT, HIDE
	
	SELECT  LOT, SUM(CONVERT(DECIMAL(13,2),LTRIM(RTRIM(SQF)))) AS SQF
	FROM @TBL_PIELES_DUPPLICADAS_FINAL
	GROUP BY  LOT 
	ORDER BY LOT

	SELECT * FROM @TBL_PIELES_DUPPLICADAS_FINAL ORDER BY LOT, HIDE
		