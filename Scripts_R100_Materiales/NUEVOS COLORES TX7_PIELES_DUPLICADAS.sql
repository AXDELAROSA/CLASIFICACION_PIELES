	-- SACAR  PIELES DUPLICADAS
	SELECT  LOT, HIDE, COUNT(*) AS N_DUPLICADA
	FROM RP_SC  (NOLOCK)
	WHERE LTRIM(RTRIM(COLOUR)) = 'FCN2DX9' 
	GROUP BY  LOT, HIDE 
	HAVING COUNT(*)>1
	ORDER BY LOT, HIDE

	-- PIES CUADRADOS POR LOTE EN MHI
