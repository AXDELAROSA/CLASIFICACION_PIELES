	DECLARE @VP_FOLIO INT = 0
	DECLARE @VP_COLOR VARCHAR(20) = ''
	DECLARE @VP_LOTE VARCHAR(20) = ''
	DECLARE @VP_HIDE VARCHAR(10) = ''
	DECLARE @VP_SQF VARCHAR(10) = ''
	DECLARE @VP_LOCACION VARCHAR(10) = ''

	DECLARE CU_PIELES_DUPLICADAS CURSOR 
	FOR SELECT TAGNO, LTRIM(RTRIM(COLOUR)), LTRIM(RTRIM(LOT)), LTRIM(RTRIM(HIDE)), LTRIM(RTRIM(SQF)), LTRIM(RTRIM(MOVEMENT))
		FROM @TBL_PIELES_DUPPLICADAS_FINAL 
		WHERE LTRIM(RTRIM(COLOUR)) = 'FCPRDX9' 
		ORDER BY ID ASC
	
	OPEN CU_PIELES_DUPLICADAS
	FETCH NEXT FROM CU_PIELES_DUPLICADAS INTO @VP_FOLIO, @VP_COLOR, @VP_LOTE, @VP_HIDE, @VP_SQF, @VP_LOCACION
	
	WHILE @@FETCH_STATUS = 0
		BEGIN	
			IF @VP_LOCACION <> 'T79'
				BEGIN
					IF (SELECT COUNT(ID) FROM RP_SC (NOLOCK) WHERE COLOUR = @VP_COLOR AND LOT = @VP_LOTE AND HIDE = @VP_HIDE ) = 0
						BEGIN
							INSERT INTO RP_SC( 
												[CDATE],[COLOUR],[LOT],[HIDE],[SQF],[TAGNO],[YARDAS],[YLB],[PESO],[TYPE],[MOVEMENT],[K_CLASIFICACION]
											)
										VALUES( GETDATE(), @VP_COLOR, @VP_LOTE, @VP_HIDE, @VP_SQF, @VP_FOLIO, NULL, NULL, NULL, 'C', @VP_LOCACION, 0
												)								
						END
				END
			FETCH NEXT FROM CU_PIELES_DUPLICADAS INTO @VP_FOLIO, @VP_COLOR, @VP_LOTE, @VP_HIDE, @VP_SQF, @VP_LOCACION
		END
	CLOSE CU_PIELES_DUPLICADAS
	DEALLOCATE CU_PIELES_DUPLICADAS

