	
	DECLARE @TBL_PIELES_DUPPLICADAS_FINAL TABLE(
	ID			INT IDENTITY(1,1),
	[COLOUR]	VARCHAR(20),
	[LOT]		VARCHAR(20),
	[HIDE]		VARCHAR(20),
	[SQF]		VARCHAR(20),
	[TAGNO]		INT,
	[TYPE]		VARCHAR(20),
	[MOVEMENT] VARCHAR(20)
	)

	INSERT INTO @TBL_PIELES_DUPPLICADAS_FINAL
	SELECT [COLOUR], [LOT], [HIDE], [SQF], [TAGNO], [TYPE], [MOVEMENT] 
	FROM RP_SC_HIDE_DELETE 
	WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUPD2' 
	AND TAGNO IN (3815708, 3825608, 3809671)
	ORDER BY LOT, HIDE

	INSERT INTO @TBL_PIELES_DUPPLICADAS_FINAL
	SELECT [COLOUR], [LOT], [HIDE], [SQF], 3475142, [TYPE], 'MHI' 
	FROM RP_SC_FOLIO_TYPE_2 
	WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUPD2' 
	AND TAGNO IN (3789866, 3789868, 3789871, 3789872, 3789893, 3789894, 3789987, 3790059, 3790064, 3790065, 3790067, 3790078)
	ORDER BY LOT, HIDE

	DECLARE @VP_FOLIO INT = 0
	DECLARE @VP_COLOR VARCHAR(20) = ''
	DECLARE @VP_LOTE VARCHAR(20) = ''
	DECLARE @VP_HIDE VARCHAR(10) = ''
	DECLARE @VP_SQF VARCHAR(10) = ''
	DECLARE @VP_LOCACION VARCHAR(10) = ''

	DECLARE CU_PIELES_DUPLICADAS CURSOR 
	FOR SELECT TAGNO, LTRIM(RTRIM(COLOUR)), LTRIM(RTRIM(LOT)), LTRIM(RTRIM(HIDE)), LTRIM(RTRIM(SQF)), LTRIM(RTRIM(MOVEMENT))
		FROM @TBL_PIELES_DUPPLICADAS_FINAL 
		WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUPD2' 
		ORDER BY ID ASC

	
	OPEN CU_PIELES_DUPLICADAS
	FETCH NEXT FROM CU_PIELES_DUPLICADAS INTO @VP_FOLIO, @VP_COLOR, @VP_LOTE, @VP_HIDE, @VP_SQF, @VP_LOCACION
	
	WHILE @@FETCH_STATUS = 0
		BEGIN	
			IF (SELECT COUNT(ID) FROM RP_SC WHERE LOT = @VP_LOTE AND HIDE = @VP_HIDE ) = 0
				BEGIN
					INSERT INTO RP_SC( 
										[CDATE],[COLOUR],[LOT],[HIDE],[SQF],[TAGNO],[YARDAS],[YLB],[PESO],[TYPE],[MOVEMENT],[K_CLASIFICACION]
									)
								VALUES( GETDATE(), @VP_COLOR, @VP_LOTE, @VP_HIDE, @VP_SQF, @VP_FOLIO, NULL, NULL, NULL, 'C', @VP_LOCACION, 0
										)
						
						
				END
			FETCH NEXT FROM CU_PIELES_DUPLICADAS INTO @VP_FOLIO, @VP_COLOR, @VP_LOTE, @VP_HIDE, @VP_SQF, @VP_LOCACION
		END
	CLOSE CU_PIELES_DUPLICADAS
	DEALLOCATE CU_PIELES_DUPLICADAS

	-- SACAR DUPLICADOS
	SELECT  LOT, HIDE, COUNT(*) 
	FROM RP_SC
	WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUPD2' 
	GROUP BY  LOT, HIDE 
	HAVING COUNT(*)>1
	ORDER BY LOT, HIDE
	
	-- PIES CUADRADOS POR LOTE EN MHI
	SELECT  LOT, SUM(CONVERT(DECIMAL(13,2),LTRIM(RTRIM(SQF)))) AS SQF
	FROM RP_SC
	WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUPD2' 
	AND MOVEMENT = 'MHI'
	GROUP BY  LOT
	ORDER BY LOT 

	-- PIES CUADRADOS POR LOTE EN MESA
	SELECT  LOT, SUM(CONVERT(DECIMAL(13,2),LTRIM(RTRIM(SQF)))) AS SQF
	FROM RP_SC
	WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUPD2' 
	AND MOVEMENT <> 'MHI'
	GROUP BY  LOT
	ORDER BY LOT 

