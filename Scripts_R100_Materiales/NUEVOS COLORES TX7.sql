SELECT  LOT, HIDE,count(*) 
FROM RP_SC_FOLIO_TYPE_2
WHERE LTRIM(RTRIM(COLOUR)) = 'FCNPJRR' 
	AND TAGNO IN (3790630, 3790631, 3790622, 3790621, 3790626, 3790632, 3790633, 3790627, 3790628, 3790629)
--AND LOT = '108702'
GROUP BY  LOT, HIDE 
HAVING COUNT(*)>1

