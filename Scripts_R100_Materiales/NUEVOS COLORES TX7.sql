-- FOLIOS DETALLADOS PARA MHI
SELECT ID, CDATE,[COLOUR],[LOT],[HIDE],[SQF],TAGNO,[YARDAS],[YLB],[PESO],TYPE,MOVEMENT,[K_CLASIFICACION] 
FROM RP_SC_FOLIO_TYPE_2 
WHERE LTRIM(RTRIM(COLOUR)) = 'FCNPDX9' 
AND TAGNO IN ( 3790407, 3790368, 3790402, 3790403, 3790406 )
AND LOT = '108702'
ORDER BY LOT, HIDE ASC

-- SE VERIFICA QUE EN LOS DETALLADOS NO SE ENCUENTREN PIELES DUPLICADAS
SELECT  LOT, HIDE,count(*) 
FROM RP_SC_FOLIO_TYPE_2
WHERE LTRIM(RTRIM(COLOUR)) = 'FCNPDX9' 
AND TAGNO IN ( 3790407, 3790368, 3790402, 3790403, 3790406 )
AND LOT = '108702'
GROUP BY  LOT, HIDE 
HAVING COUNT(*)>1

