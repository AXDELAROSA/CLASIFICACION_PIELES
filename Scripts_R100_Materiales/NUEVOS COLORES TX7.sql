-- FOLIOS DETALLADOS PARA MHI
SELECT CDATE,[COLOUR],[LOT],[HIDE],[SQF],TAGNO,[YARDAS],[YLB],[PESO],TYPE,MOVEMENT,[K_CLASIFICACION] 
FROM RP_SC_FOLIO_TYPE_2 
WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUML8' 
AND TAGNO IN (3789869, 3789870)
ORDER BY HIDE ASC

-- SE VERIFICA QUE EN LOS DETALLADOS NO SE ENCUENTREN PIELES DUPLICADAS
SELECT  LOT, HIDE,count(*) 
FROM RP_SC_FOLIO_TYPE_2
WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUML8' 
AND TAGNO IN (3789869, 3789870)
GROUP BY  LOT, HIDE 
HAVING COUNT(*)>1

