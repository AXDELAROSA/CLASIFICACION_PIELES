-- FOLIOS DETALLADOS PARA MHI
SELECT ID, CDATE,[COLOUR],[LOT],[HIDE],[SQF],TAGNO,[YARDAS],[YLB],[PESO],TYPE,MOVEMENT,[K_CLASIFICACION] 
FROM RP_SC_FOLIO_TYPE_2 
WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUDX9' 
AND TAGNO IN ( 3790344, 3790354 )
AND ID IN (4739936, 4740005, 4740004, 4739943)
ORDER BY LOT, HIDE ASC

-- SE VERIFICA QUE EN LOS DETALLADOS NO SE ENCUENTREN PIELES DUPLICADAS
SELECT  LOT, HIDE,count(*) 
FROM RP_SC_FOLIO_TYPE_2
WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUDX9' 
AND TAGNO IN ( 3790344, 3790354 )
GROUP BY  LOT, HIDE 
HAVING COUNT(*)>1

-- SACAN LOS PIES CUADRADOS POR LOTE PARA ACTUALIZAR EL STOCK
SELECT   [LOT], SUM(CONVERT(DECIMAL(13,2),LTRIM(RTRIM(SQF)))) AS SQF
FROM RP_SC_FOLIO_TYPE_2 
WHERE LTRIM(RTRIM(COLOUR)) = 'FNRUDX9' 
AND TAGNO IN ( 3790344, 3790354 )
GROUP BY LOT
ORDER BY LOT

